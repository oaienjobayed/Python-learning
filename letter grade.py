### letter grade
marks = 85

if marks >= 80:
    grade = "A+"
    gpa = 5.0
elif marks >= 70:
      grade = "A"
      gpa = 4.0
else:
    grade = "B"
    gpa = 3.0

print(f"grade is {grade}, GPA is {gpa}")

